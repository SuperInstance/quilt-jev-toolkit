// vendor-chrono-fixture.mjs — generate the committed chrono fixture (lane 68-a)
//
//   node scripts/vendor-chrono-fixture.mjs
//
// Builds a small, fully deterministic chrono sheet (fixed clock, fixed values,
// no network) with quilt-chrono's OWN exports — Ledger (src/ledger.js) and
// seal (src/seal.js) — then commits the sealed chain sidecar + checkpoint to
// tests/fixtures/chrono-fixture.json so that:
//
//   1. the organ suite can prove bootChrono round-trips a REAL chrono seal
//      without quilt-chrono being present (the sibling repo is optional at
//      test time — the fixture carries the bytes; the FORMAT is the contract);
//   2. the fixture is generated BY the substrate, never hand-written — the
//      provenance block names the generator, the source repo commit, and the
//      exact demo script, so regenerating is one command.
//
// The HMAC key below is a TEST-ONLY fixture key (its name says so); it is not
// a credential and guards nothing. Regenerate after intentional changes to
// the demo sheet — the fixture is data, the generator is its law.
//
// Cross-repo import: quilt-chrono lives at ../quilt-chrono relative to this
// repo (both are SuperInstance fleet repos checked out side by side). The
// import here is a GENERATION-TIME dependency only — nothing in src/ or the
// test suite imports chrono at runtime except the skip-if-absent live test.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execSync } from "node:child_process";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const chronoRoot = path.resolve(repoRoot, "..", "quilt-chrono");
const outFile = path.join(repoRoot, "tests", "fixtures", "chrono-fixture.json");

const FIXTURE_KEY = "chrono-fixture-key-test-only-not-a-credential";

const { Ledger, Clock } = await import(pathToFileURL(path.join(chronoRoot, "src", "ledger.js")).href);
const { seal } = await import(pathToFileURL(path.join(chronoRoot, "src", "seal.js")).href);

// --- the demo sheet (deterministic: fixed clock, step 1s, no noise) ---------
// It exercises every row of the §9 mapping:
//   seq 0  write sensor.temp (cause init)   → init receipt        (R2)
//   seq 1  read  sensor.temp (cause pull)   → witness receipt     (R1)
//   seq 2  write sensor.temp (cause set)    → set receipt         (R3)
//   seq 3  read  sensor.temp (push source)  → witness (the pair)  (R4)
//   seq 4  write sink.display (push sink)   → set (the pair)      (R4)
//   seq 5  read  ghost.cell  (value null)   → witness null        (R1)
//   seq 6  write sink.display (cause set)   → set receipt         (R3)
const clock = new Clock({ startMs: Date.parse("2026-01-01T00:00:00.000Z"), stepMs: 1000 });
const ledger = new Ledger({ name: "chrono-demo", clock });

ledger.append({ op: "write", cell: "sensor.temp", value: 21.5, by: "engine:init", cause: "init", pushed: false, flow_id: null });
ledger.append({ op: "read", cell: "sensor.temp", value: 21.5, by: "agent:operator", cause: "pull", pushed: false, flow_id: null });
ledger.append({ op: "write", cell: "sensor.temp", value: 22.1, by: "agent:operator", cause: "set", pushed: false, flow_id: null });
const push = ledger.recordFlow({ from: "sensor.temp", to: "sink.display", value: 22.1, by: "engine:wire", cause: "push", edge: "sensor.temp->sink.display" });
ledger.append({ op: "read", cell: "ghost.cell", value: null, by: "agent:operator", cause: "pull", pushed: false, flow_id: null });
ledger.append({ op: "write", cell: "sink.display", value: 22.4, by: "agent:operator", cause: "set", pushed: false, flow_id: null });

if (push.read.flow_id !== push.write.flow_id) {
  throw new Error("fixture generation broke its own push pair");
}

// --- seal at the tip with chrono's own seal ---------------------------------
const sealed = seal(ledger, { key: FIXTURE_KEY, name: "chrono-demo" });

// independent expectation: the write-fold (chrono's own cellsAt law) —
// recomputed here from the entries so the fixture carries its own oracle.
const expectedCells = {};
for (const e of ledger.entries) {
  if (e.op === "write") expectedCells[e.cell] = { kind: "value", value: e.value };
}

const chronoHead = execSync("git rev-parse HEAD", { cwd: chronoRoot }).toString().trim();

const fixture = {
  provenance: {
    generator: "scripts/vendor-chrono-fixture.mjs",
    generatedBy: "lane 68-a (wave-68)",
    source: "SuperInstance/quilt-chrono",
    sourceCommit: chronoHead,
    sourceModules: ["src/ledger.js", "src/seal.js"],
    clock: "Clock({ startMs: 2026-01-01T00:00:00.000Z, stepMs: 1000 }) — fully deterministic",
    keyNote: "the seal key is a test-only fixture key, not a credential; it lives in the test suite and this generator",
    demoSheet: "7 entries: init-write, pull-read, set-write, push pair (read+write), null-read, set-write; sealed at the tip",
  },
  key: FIXTURE_KEY,
  organId: sealed.checkpoint.manifest.organId,
  manifestHash: sealed.checkpoint.manifestHash,
  chainTip: sealed.checkpoint.hash,
  checkpoint: sealed.checkpoint,
  links: sealed.links,
  expectedCellsAtTip: expectedCells,
};

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, JSON.stringify(fixture, null, 2) + "\n", "utf8");
console.log(`fixture written: ${outFile}`);
console.log(`  entries: ${ledger.entries.length}, links: ${sealed.links.length}, boundary: ${sealed.checkpoint.seq}`);
console.log(`  organId: ${fixture.organId}, chainTip: ${fixture.chainTip.slice(0, 16)}…`);
